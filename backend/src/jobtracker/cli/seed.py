"""Fake data for local UI work. Fictional companies, example.com addresses."""

from __future__ import annotations

from datetime import timedelta
from zoneinfo import ZoneInfo

from jobtracker.core import services
from jobtracker.core.models import (
    Event,
    EventKind,
    EventType,
    InterviewNote,
    MatchMethod,
    Origin,
)
from jobtracker.core.ports import Clock, Repository

SAMPLES = [
    # company, role, days ago, channel, seniority, stack, emails: (days ago, type, round, interview in days)
    ("Acme Robotics", "Senior Backend Engineer", 30, "direct", "senior", ["python", "aws"],
     [(29, EventType.APPLICATION_RECEIVED, None, None), (20, EventType.SCREENING_INVITE, None, None),
      (12, EventType.INTERVIEW_SCHEDULED, 1, -10), (3, EventType.INTERVIEW_SCHEDULED, 2, 2)]),
    ("Globex Data", "Software Engineer, Platform", 25, "linkedin", "mid", ["go", "kubernetes"],
     [(25, EventType.APPLICATION_RECEIVED, None, None), (15, EventType.REJECTION, None, None)]),
    ("Initech", "Full Stack Engineer", 40, "referral", "senior", ["typescript", "react", "python"],
     [(39, EventType.APPLICATION_RECEIVED, None, None)]),
    ("Umbrella Health", "Backend Engineer (Python)", 18, "direct", "senior", ["python", "postgres"],
     [(17, EventType.APPLICATION_RECEIVED, None, None), (9, EventType.ASSESSMENT, None, None),
      (2, EventType.INTERVIEW_INVITE, 2, None)]),
    ("Hooli", "Staff Engineer", 50, "recruiter", "staff", ["java", "distributed systems"],
     [(48, EventType.RECRUITER_OUTREACH, None, None), (40, EventType.INTERVIEW_SCHEDULED, 1, -38),
      (30, EventType.REJECTION, None, None)]),
    ("Vandelay Logistics", "Python Developer", 6, "direct", "mid", ["python", "django"],
     [(6, EventType.APPLICATION_RECEIVED, None, None)]),
]  # fmt: skip


def seed(repo: Repository, clock: Clock, tz: ZoneInfo) -> int:
    if repo.get_event_by_message_id("<seed-acme-0@example.com>"):
        raise RuntimeError("sample data already loaded")
    now = clock.now()
    for company, role, days, channel, seniority, stack, emails in SAMPLES:
        slug = company.split()[0].lower()
        app = services.create_application(
            repo,
            clock,
            services.ApplicationInput(
                company=company,
                role_title=role,
                job_url=f"https://jobs.example.com/{slug}/{role.lower().replace(' ', '-')}",
                company_domain=f"{slug}.example.com",
                source_ats="greenhouse" if channel == "direct" else None,
                source_channel=channel,
                seniority=seniority,
                stack=stack,
                applied_at=now - timedelta(days=days),
            ),
            Origin.MANUAL,
        )
        for i, (ago, etype, round_, interview_in) in enumerate(emails):
            at = now - timedelta(days=ago)
            repo.add_event(
                Event(
                    kind=EventKind.EMAIL,
                    event_type=etype,
                    occurred_at=at,
                    application_id=app.id,
                    message_id=f"<seed-{slug}-{i}@example.com>",
                    gm_thread_id=f"seed-{slug}",
                    from_address=f"recruiting@{slug}.example.com",
                    from_name=f"{company} Recruiting",
                    subject=f"[sample] {etype.value.replace('_', ' ')}: {role}",
                    snippet="Sample email generated by `jobtracker dev seed`.",
                    round=round_,
                    interview_at=now + timedelta(days=interview_in)
                    if interview_in is not None
                    else None,
                    needs_reply=etype == EventType.INTERVIEW_INVITE,
                    summary=f"Sample {etype.value} for {role}.",
                    confidence=0.95,
                    match_method=MatchMethod.ALIAS,
                    assigned_by="auto",
                    created_at=now,
                )
            )
        services.recompute(repo, clock, app.id)

    acme = next(a for a in repo.list_applications() if a.company_name == "Acme Robotics")
    repo.save_note(
        InterviewNote(
            application_id=acme.id,
            round=1,
            interview_at=now - timedelta(days=10),
            interview_type="technical",
            questions=["Design a rate limiter", "Explain Postgres MVCC"],
            self_rating=3,
            went_well="Clear API design",
            went_wrong="Hesitated on isolation levels",
            topics_to_study=["postgres isolation levels", "rate limiting algorithms"],
            created_at=now,
            updated_at=now,
        )
    )
    repo.add_event(
        Event(
            kind=EventKind.EMAIL,
            event_type=EventType.INTERVIEW_INVITE,
            occurred_at=now - timedelta(days=1),
            message_id="<seed-unassigned-1@example.com>",
            gm_thread_id="seed-unassigned",
            from_address="no-reply@ashbyhq.com",
            from_name="Talent Team",
            subject="[sample] Next steps for your application",
            snippet="We'd love to schedule a first conversation. Please pick a time.",
            needs_reply=True,
            summary="Interview invite from an unknown company via Ashby.",
            confidence=0.4,
            extraction={"company": None, "role": "Software Engineer", "event_type": "interview_invite",
                        "confidence": 0.4, "is_job_related": True},
            match_method=MatchMethod.NONE,
            created_at=now,
        )
    )  # fmt: skip
    review = services.create_application(
        repo,
        clock,
        services.ApplicationInput(
            company="Stark Analytics",
            role_title="Data Engineer",
            applied_at=now - timedelta(days=2),
        ),
        Origin.EMAIL,
    )
    review.needs_review = True
    repo.update_application(review)
    return len(SAMPLES) + 1
